  ButterflyIcon,
  CarrotIcon,
  CompassIcon,
  CrosshairIcon,
  CubeIcon,
  DropIcon,
  FireIcon,
  FishSimpleIcon,
  FlameIcon,
  GavelIcon,
  HammerIcon,
  HardHatIcon,
  LightningIcon,
  PaintBrushIcon,
